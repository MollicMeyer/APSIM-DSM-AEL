# Local integration test: independent SQL yield calculation and checkpoint recovery.
here<-dirname(normalizePath(sub('^--file=','',grep('^--file=',commandArgs(FALSE),value=TRUE)),winslash='/'))
source(file.path(here,'../R/common.R'));library(DBI);library(RSQLite)
a<-args_named();experiment<-normal(need(a,'experiment'));out<-normal(need(a,'out'),FALSE)
stopifnot(!dir.exists(out));dir.create(out,recursive=TRUE)
m<-read.csv(file.path(experiment,'manifest.csv'));stopifnot(nrow(m)==2)
runner<-file.path(R.home('bin'),'Rscript.exe');script<-normal(file.path(here,'../R/extract.R'))
invoke<-function(dest,extra=character())system2(runner,c(shQuote(script),'--experiment',shQuote(experiment),'--out',shQuote(dest),'--test-mode','yes',extra),stdout=file.path(out,paste0(basename(dest),'_',length(extra),'.stdout.txt')),stderr=file.path(out,paste0(basename(dest),'_',length(extra),'.stderr.txt')))
fresh<-file.path(out,'fresh');resumed<-file.path(out,'resumed')
stopifnot(invoke(fresh)==0)
stopifnot(invoke(resumed,c('--test-stop-after','1'))!=0)
stopifnot(!file.exists(file.path(resumed,'status.json')),length(list.files(file.path(resumed,'checkpoints'),pattern='[.]rds$'))==1)
stopifnot(invoke(resumed,c('--resume','yes'))==0)
csv<-list.files(fresh,pattern='[.]csv$',recursive=TRUE)
stopifnot(all(unname(tools::md5sum(file.path(fresh,csv)))==unname(tools::md5sum(file.path(resumed,csv)))))
stopifnot(invoke(resumed,c('--resume','yes'))==0)
aa<-read.csv(file.path(fresh,'annual_stocks_and_yields.csv'))
for(i in seq_len(nrow(m))){
 con<-dbConnect(SQLite(),m$expected_db[i],flags=SQLITE_RO)
 direct<-dbGetQuery(con,"SELECT CAST(substr(Date,1,4) AS INTEGER) AS year, MAX(MaizeGrain)*0.01 AS grain FROM WarmupDaily GROUP BY substr(Date,1,4) ORDER BY year")
 dbDisconnect(con);q<-aa[aa$run_id==m$run_id[i],];q<-q[order(q$year),]
 stopifnot(identical(q$year,direct$year),max(abs(q$Maize_peak_grain_Mg_ha-direct$grain))<1e-10)
}
writej(list(status='PASS',profiles=2,independent_SQL_yields=TRUE,interrupted_checkpoint_resume=TRUE,idempotent_resume=TRUE,identical_CSV_hashes=TRUE,extractor_md5=md5(script)),file.path(out,'QA.json'))
cat('Extraction integration tests PASS\n')
